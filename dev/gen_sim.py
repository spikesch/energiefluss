def watts_expr(key: str, unit: str) -> str:
    factor = " * 1000" if unit == "kW" else ""
    return f"(states('input_number.sim_{key}') | float(0)){factor}"


def grid_template() -> str:
    terms = []
    for key, _n, _a, _b, _s, unit, _i, _k, group in SIMS:
        if group == "load":
            terms.append(f"+ {watts_expr(key, unit)}")
        elif group == "bat":
            terms.append(f"+ {watts_expr(key, unit)}")
        elif group == "bat_inv":
            terms.append(f"- {watts_expr(key, unit)}")
        elif group == "pv":
            terms.append(f"- {watts_expr(key, unit)}")
    return "{{ (0 " + " ".join(terms) + ") | round(1) }}"


def main() -> None:
    out = [
        "# AUTO-GENERATED by dev/gen_sim.py - test instance only.",
        "homeassistant:",
        # extra YAML kept on the NAS only (e.g. packages/live_spiegel.yaml: real
        # values mirrored read-only from the live HA; its token is in secrets.yaml)
        "  packages: !include_dir_named packages",
        "  name: Energiefluss Dev",
        "  time_zone: Europe/Berlin",
        "  country: DE",
        "  unit_system: metric",
        "",
        "default_config:",
        "",
        "logger:",
        "  default: warning",
        "  logs:",
        "    custom_components.energiefluss: debug",
        "",
        "input_number:",
    ]
    for key, name, mn, mx, st, unit, init, kind, _g in SIMS:
        out += [
            f"  sim_{key}:",
            f'    name: "Sim {name}"',
            f"    min: {mn}",
            f"    max: {mx}",
            f"    step: {st}",
            f"    initial: {init}",
            f'    unit_of_measurement: "{unit}"',
            "    mode: box" if kind in ("energy", "monetary") else "    mode: slider",
        ]
    out += ["", "template:", "  - sensor:"]
    for key, name, _a, _b, _s, unit, _i, kind, _g in SIMS:
        if key == "grundlast" or kind == "hidden":
            continue  # unmeasured on purpose / exposed differently below
        state = f"{{{{ states('input_number.sim_{key}') }}}}"
        if key == "load_neubau":
            state = (
                "{{ ((states('input_number.sim_load_neubau') | float(0))"
                " + (states('input_number.sim_load_wasserkocher') | float(0))) | round(1) }}"
            )
        out += [
            f'      - name: "{name}"',
            f"        unique_id: sim_{key}",
            f"        state: \"{state}\"",
            f'        unit_of_measurement: "{unit}"',
        ]
        out += {
            "power": ["        device_class: power", "        state_class: measurement"],
            "battery": ["        device_class: battery", "        state_class: measurement"],
            "energy": ["        device_class: energy", "        state_class: total"],
            "monetary": ["        device_class: monetary"],
        }[kind]
    out += [
        '      - name: "Netz Leistung"',
        "        unique_id: sim_grid_power",
        f"        state: >-\n          {grid_template()}",
        '        unit_of_measurement: "W"',
        "        device_class: power",
        "        state_class: measurement",
    ]
    # Split sensors like Tibber Pulse (power / power_production) and like a
    # battery that reports charging and discharging separately, plus a
    # measured house consumption (base load + all loads).
    grid = "(" + grid_template()[3:-3] + ")"
    bat4 = watts_expr("bat4_power", "W")
    house = " + ".join(watts_expr(k, u) for k, _n, _a, _b, _s, u, _i, _k, g in SIMS if g == "load")
    for name, uid, expr in (
        ("Tibber Bezug", "sim_tibber_power", f"[{grid}, 0] | max"),
        ("Tibber Einspeisung", "sim_tibber_power_production", f"[-{grid}, 0] | max"),
        ("Speicher 4 Laden", "sim_bat4_charge", f"[{bat4}, 0] | max"),
        ("Speicher 4 Entladen", "sim_bat4_discharge", f"[-{bat4}, 0] | max"),
        ("Haus Leistung gemessen", "sim_house_power", f"({house}) | round(1)"),
    ):
        out += [
            f'      - name: "{name}"',
            f"        unique_id: {uid}",
            "        state: >-",
            f"          {{{{ {expr} }}}}",
            '        unit_of_measurement: "W"',
            "        device_class: power",
            "        state_class: measurement",
        ]
    target = Path(__file__).parent / "config" / "configuration.yaml"
    target.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(SIMS)} sliders -> {target}")


if __name__ == "__main__":
    main()
