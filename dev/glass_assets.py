"""Turn the generated glass pictures into card assets.

For each picture in dev/assets (car, inverter and solar source) the flat
background is removed with "colour to alpha" (every pixel is treated as a mix
of the background colour and the object, so soft glass edges and shadows keep
their transparency), the object is cropped and scaled, and the points from the
matching JSON file (outline, connectors, text positions, all in source pixels)
are written to a TypeScript module in the picture's own output pixels.

Output: frontend/public/<name>-glass.png and frontend/src/<name>-asset.ts (car, inverter, solar),
        docs/logo.png and docs/brand/icon(@2x).png from icon-source.jpg

Run: python dev/glass_assets.py
"""

import json
import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "dev" / "assets"
PUBLIC = ROOT / "frontend" / "public"
SRC_TS = ROOT / "frontend" / "src"
MARGIN = 6  # px around the object in source pixels
NOISE = 8  # alpha (0..255) below this is background noise of the jpeg
TOLERANCE = 6  # colour difference (0..255) still counted as background


def colour_to_alpha(rgb: np.ndarray, bg: np.ndarray) -> np.ndarray:
    p = rgb / 255.0
    b = bg / 255.0
    tol = TOLERANCE / 255.0  # jpeg noise around the flat background
    up = np.where(p > b, np.maximum(p - b - tol, 0) / np.maximum(1 - b, 1e-6), 0)
    down = np.where(p < b, np.maximum(b - p - tol, 0) / np.maximum(b, 1e-6), 0)
    alpha = np.clip(np.max(np.maximum(up, down), axis=-1), 0, 1)
    a = alpha[..., None]
    fg = np.where(a > 1e-4, (p - b) / np.maximum(a, 1e-4) + b, 0)
    out = np.concatenate([np.clip(fg, 0, 1), a], axis=-1)
    return (out * 255).round().astype(np.uint8)


def cut_out(src: Path, out_png: Path, width: int):
    """Remove the background, crop, scale; returns a source -> output point mapper."""
    rgb = np.asarray(Image.open(src).convert("RGB")).astype(float)
    corners = np.concatenate([rgb[:24, :24], rgb[:24, -24:], rgb[-24:, :24], rgb[-24:, -24:]]).reshape(-1, 3)
    bg = np.median(corners, axis=0)
    rgba = colour_to_alpha(rgb, bg)
    a = rgba[..., 3].astype(float)
    rgba[..., 3] = np.clip((a - NOISE) * 255 / (255 - NOISE), 0, 255).astype(np.uint8)
    ys, xs = np.nonzero(rgba[..., 3] > 40)
    x0, x1 = int(max(xs.min() - MARGIN, 0)), int(min(xs.max() + MARGIN, rgb.shape[1] - 1))
    y0, y1 = int(max(ys.min() - MARGIN, 0)), int(min(ys.max() + MARGIN, rgb.shape[0] - 1))
    crop = Image.fromarray(rgba[y0 : y1 + 1, x0 : x1 + 1], "RGBA")
    scale = width / crop.width
    height = round(crop.height * scale)
    crop.resize((width, height), Image.LANCZOS).save(out_png, optimize=True)
    print(f"{src.name}: background {bg.round()}, crop {x0},{y0}-{x1},{y1}, out {width}x{height}, {out_png.stat().st_size // 1024} KB")

    def pt(xy: list[float]) -> list[float]:
        return [round(float(xy[0] - x0) * scale, 1), round(float(xy[1] - y0) * scale, 1)]

    return pt, height, scale


def write_ts(path: Path, comment: list[str], const: str, fields: list[str]) -> None:
    lines = ["// Generated by dev/glass_assets.py - do not edit.", *[f"// {c}" for c in comment], f"export const {const} = {{"]
    lines += [f"  {f}," for f in fields]
    lines += ["};", ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def car() -> None:
    width = 420  # shown at about 120 px, sharp on 3x screens
    pt, height, scale = cut_out(ASSETS / "car-source.jpg", PUBLIC / "car-glass.png", width)
    spec = json.loads((ASSETS / "car-tank.json").read_text())
    tank = [pt(p) for p in spec["tank"]]
    write_ts(
        SRC_TS / "car-asset.ts",
        [
            "The glass car picture (frontend/public/car-glass.png) and, in the picture's own",
            "pixels: the outline of the car body (clips the liquid), the car's floor and the",
            "liquid height, where the two values are written on the plate, and where the",
            "feed line enters the wallbox.",
        ],
        "CAR_IMAGE",
        [
            'file: "car-glass.png"',
            f"width: {width}",
            f"height: {height}",
            'tank: "' + " ".join(f"{x},{y}" for x, y in tank) + '"',
            f"floorQuad: {[pt(p) for p in spec['floor_quad']]} as [number, number][]",
            f"liquidHeight: {round(spec['liquid_height'] * scale, 1)}",
            f"powerText: {pt(spec['power_text'])} as [number, number]",
            f"energyText: {pt(spec['energy_text'])} as [number, number]",
            f"edgeAngle: {spec['edge_angle']}",
            f"wallboxTop: {pt(spec['wallbox_top'])} as [number, number]",
        ],
    )


def inverter() -> None:
    width = 300  # shown at about 80 px
    pt, height, _scale = cut_out(ASSETS / "inverter-source.jpg", PUBLIC / "inverter-glass.png", width)
    spec = json.loads((ASSETS / "inverter.json").read_text())
    write_ts(
        SRC_TS / "inverter-asset.ts",
        [
            "The glass inverter picture (frontend/public/inverter-glass.png) and the tips of",
            "its connectors in the picture's own pixels: top = house, bottom = storage,",
            "left = PV, grid, wallbox (top to bottom).",
        ],
        "INVERTER_IMAGE",
        [
            'file: "inverter-glass.png"',
            f"width: {width}",
            f"height: {height}",
            f"top: {pt(spec['top'])} as [number, number]",
            f"bottom: {pt(spec['bottom'])} as [number, number]",
            f"left: {[pt(p) for p in spec['left']]} as [number, number][]",
        ],
    )


def solar() -> None:
    width = 360  # shown at about 130 px
    pt, height, _scale = cut_out(ASSETS / "solar-source.jpg", PUBLIC / "solar-glass.png", width)
    spec = json.loads((ASSETS / "solar.json").read_text())
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = spec["face"]

    def at(u: float, v: float) -> list[float]:
        top = (x0 + (x1 - x0) * u, y0 + (y1 - y0) * u)
        bottom = (x3 + (x2 - x3) * u, y3 + (y2 - y3) * u)
        return pt([top[0] + (bottom[0] - top[0]) * v, top[1] + (bottom[1] - top[1]) * v])

    # string order of the card: top row left, right, bottom row left, right
    spots = [at(0.25, 0.27), at(0.75, 0.27), at(0.25, 0.73), at(0.75, 0.73)]
    # directions of the face's top edge and left edge (unit vectors): labels are
    # drawn in this frame so they lie flat on the panel
    def unit(dx: float, dy: float) -> list[float]:
        n = math.hypot(dx, dy)
        return [round(dx / n, 4), round(dy / n, 4)]

    across = unit(x1 - x0, y1 - y0)
    down = unit(x3 - x0, y3 - y0)
    write_ts(
        SRC_TS / "solar-asset.ts",
        [
            "The glass solar panel picture (frontend/public/solar-glass.png) and, in its own",
            "pixels, the middles of the four quarters of its front face (the string labels)",
            "and the directions of the face's top and left edge; face = its corners (top left,",
            "top right, bottom right, bottom left).",
        ],
        "SOLAR_IMAGE",
        [
            'file: "solar-glass.png"',
            f"width: {width}",
            f"height: {height}",
            f"face: {[pt(c) for c in spec['face']]} as [number, number][]",
            f"spots: {spots} as [number, number][]",
            f"across: {across} as [number, number]",
            f"down: {down} as [number, number]",
        ],
    )


def icon() -> None:
    """The app icon: the rounded glass square cut out of icon-source.jpg (corners
    transparent), as README logo and in the sizes of the home-assistant/brands repo."""
    src = Image.open(ASSETS / "icon-source.jpg").convert("RGB")
    box = ICON_BOX
    face = src.crop(box)
    size = face.width
    # anti-aliased rounded-square mask, drawn 4x and scaled down
    big = Image.new("L", (size * 4, size * 4), 0)
    ImageDraw.Draw(big).rounded_rectangle((0, 0, size * 4 - 1, size * 4 - 1), radius=ICON_RADIUS * 4, fill=255)
    face.putalpha(big.resize((size, size), Image.LANCZOS))
    # docs/brand for the README, custom_components/<domain>/brand for HACS / Home Assistant
    for out in (ROOT / "docs" / "brand", ROOT / "custom_components" / "energiefluss" / "brand"):
        out.mkdir(parents=True, exist_ok=True)
        for name, px in (("icon.png", 256), ("icon@2x.png", 512)):
            face.resize((px, px), Image.LANCZOS).save(out / name, optimize=True)
    face.resize((256, 256), Image.LANCZOS).save(ROOT / "docs" / "logo.png", optimize=True)
    print(f"icon-source.jpg: box {box}, out docs/logo.png, docs/brand/icon.png, icon@2x.png")


# the glass square in icon-source.jpg (including its 2.5D edge) and its corner radius
ICON_BOX = (118, 118, 906, 906)
ICON_RADIUS = 110


if __name__ == "__main__":
    car()
    inverter()
    solar()
    icon()
